export function contactMessage(serviceName?: string): string {
  const service = serviceName?.trim();
  return service
    ? `Здравствуйте, Виктория! Хочу забронировать баню: ${service}${/[.!?]$/.test(service) ? '' : '.'} Подскажите, пожалуйста, стоимость и подтвердите свободное время.`
    : 'Здравствуйте, Виктория! Хочу забронировать баню. Подскажите, пожалуйста, свободные даты и стоимость аренды по часам или со спальней на сутки.';
}
